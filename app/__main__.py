"""Entry point: `python -m app` serves the API on 127.0.0.1:8000 (loopback only).

The per-launch token is printed once at startup. Pass VITRA_API_TOKEN to reuse a
value generated by a launcher script; otherwise a fresh random one is made.
"""

from __future__ import annotations

import argparse
import logging
import sys
from dataclasses import replace

import uvicorn

from .config import NonLoopbackError, Settings, parse_prediction_sets
from .main import create_app


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m app", description="Vitra local API (loopback only)."
    )
    ap.add_argument(
        "--predictions",
        metavar="SETS",
        help='prediction sets to load: "all" (default: every *.jsonl in data/derived/predictions), '
        '"none", or a comma list of names or .jsonl paths, e.g. "test,unlabeled". '
        "Same as VITRA_PREDICTIONS.",
    )
    args = ap.parse_args(argv)
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s"
    )
    logging.getLogger("httpx").setLevel(logging.WARNING)  # health probes are not news
    try:
        settings = Settings.from_env()
        if args.predictions is not None:
            settings = replace(settings, predictions=parse_prediction_sets(args.predictions))
    except NonLoopbackError as exc:
        print(f"[vitra] {exc}", file=sys.stderr)
        return 2
    app = create_app(settings)
    print(f"[vitra] API on http://{settings.bind_host}:{settings.port} (loopback only)", flush=True)
    print(f"[vitra] X-Vitra-Token for this launch: {settings.token}", flush=True)
    print("[vitra] For the web dev server: VITE_VITRA_TOKEN=<token above> npm run dev", flush=True)
    # access_log=False: uvicorn's access log prints query strings.
    # Our middleware logs the path only.
    uvicorn.run(
        app,
        host=settings.bind_host,
        port=settings.port,
        access_log=False,
        log_config=None,
        server_header=False,
        proxy_headers=False,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
